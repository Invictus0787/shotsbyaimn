function f(
  n: number,
  x: string,
  y: string,
  w: string,
  rot: number,
  z: number,
): HeroFrame {
  const [nw, nh] = SIZE[n];
  return {
    src: `/images/hero/collage/${pad(n)}.jpg`,
    x,
    y,
    w,
    rot,
    z,
    nw,
    nh,
  };
}

